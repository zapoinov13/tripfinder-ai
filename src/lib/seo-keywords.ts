/**
 * Как люди ищут то, что мы продаём.
 *
 * Формулировки взяты не из головы: это то, чем озаглавлены страницы,
 * которые уже стоят в выдаче по нашим темам. Отсюда и порядок слов —
 * «экскурсии в Дубае на русском языке», «аренда авто в Дубае без депозита»,
 * «снять квартиру в Дубае посуточно», «горящие туры в Дубай из Алматы».
 * Совпадение с запросом человека начинается с заголовка, поэтому заголовки
 * страниц собираются здесь, а не пишутся на каждой странице заново.
 *
 * Правило: обещаем только то, что на странице есть. Пустой раздел с
 * заголовком «187 экскурсий» — обман и для человека, и для поисковика,
 * поэтому число в заголовок подставляется живое, а когда его нет —
 * формулировка меняется.
 */

import { matchesQuery } from "@/lib/search-text";

/** Разделы витрин: по ним же строятся адреса. */
export type Vertical = "tours" | "excursions" | "stays" | "cars" | "sport" | "assistance";

export type VerticalSeo = {
  /** Что это в одном слове: «экскурсии», «жильё». */
  noun: string;
  /** Родительный падеж для счётчиков: «12 экскурсий». */
  nounGenitive: string;
  /** Заголовок раздела без города. */
  title: string;
  /** Заголовок с городом: «Экскурсии в Дубае». */
  titleInCity: (city: string) => string;
  /** Описание раздела: первые 160 символов попадут в сниппет. */
  description: (city?: string) => string;
  /** Хвост запроса, которым люди уточняют: «на русском языке», «без депозита». */
  qualifiers: string[];
  /** Слова, по которым этот раздел ищут внутри сайта. */
  keywords: string[];
};

/** Дубай → «в Дубае»: заголовок «Экскурсии в Дубай» читается как ошибка. */
export function inCity(city: string): string {
  const map: Record<string, string> = {
    Дубай: "Дубае",
    "Абу-Даби": "Абу-Даби",
    Шарджа: "Шардже",
    Анталия: "Анталии",
    Стамбул: "Стамбуле",
    Пхукет: "Пхукете",
    Бангкок: "Бангкоке",
    Хургада: "Хургаде",
    "Шарм-эль-Шейх": "Шарм-эль-Шейхе",
    Нячанг: "Нячанге",
    Тбилиси: "Тбилиси",
    Батуми: "Батуми",
    Доха: "Дохе",
    Бали: "Бали",
    Мале: "Мале",
    Коломбо: "Коломбо",
    Алматы: "Алматы",
    Астана: "Астане",
    Шымкент: "Шымкенте",
  };
  if (map[city]) return map[city];
  // Общее правило русского предложного падежа для городов на согласную.
  if (/[бвгджзклмнпрстфхцчшщ]$/i.test(city)) return `${city}е`;
  if (/й$/i.test(city)) return `${city.slice(0, -1)}е`;
  if (/а$/i.test(city)) return `${city.slice(0, -1)}е`;
  return city;
}

/** «в Дубай» — куда едут: для туров направление, а не место. */
export function toCountry(country: string): string {
  const map: Record<string, string> = {
    ОАЭ: "ОАЭ",
    Турция: "Турцию",
    Таиланд: "Таиланд",
    Египет: "Египет",
    Вьетнам: "Вьетнам",
    Мальдивы: "Мальдивы",
    Грузия: "Грузию",
    Катар: "Катар",
    "Шри-Ланка": "Шри-Ланку",
    Индонезия: "Индонезию",
  };
  return map[country] ?? country;
}

